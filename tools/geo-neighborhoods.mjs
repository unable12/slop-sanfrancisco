// Rebuild from the pinned DataSF Analysis Neighborhoods snapshot (j2bu-swwd).
import fs from 'node:fs';
import crypto from 'node:crypto';
import { toWorld, pointInRing } from './geo-base.mjs';
const raw=fs.readFileSync(new URL('../data/raw/neighborhoods-p7.geojson',import.meta.url));
const input=JSON.parse(raw);
const neighborhoods=input.features.map(f=>{
  const polygons=(f.geometry.type==='Polygon'?[f.geometry.coordinates]:f.geometry.coordinates)
    .map(p=>p.map(r=>r.map(([lon,lat])=>toWorld(lon,lat).map(n=>Math.round(n*10)/10))));
  const vertices=polygons.flatMap(p=>p[0]),xs=vertices.map(p=>p[0]),zs=vertices.map(p=>p[1]);
  const bounds=[Math.min(...xs),Math.min(...zs),Math.max(...xs),Math.max(...zs)];
  let label=[(bounds[0]+bounds[2])/2,(bounds[1]+bounds[3])/2];
  const inside = q => polygons.some(p => pointInRing(q[0],q[1],p[0]) && !p.slice(1).some(r => pointInRing(q[0],q[1],r)));
  if (!inside(label)) {
    const candidates = [];
    for (let j=1;j<40;j++) for (let i=1;i<40;i++) {
      const q=[bounds[0]+i*(bounds[2]-bounds[0])/40,bounds[1]+j*(bounds[3]-bounds[1])/40];
      if (inside(q)) candidates.push(q);
    }
    candidates.sort((a,b)=>Math.hypot(a[0]-label[0],a[1]-label[1])-Math.hypot(b[0]-label[0],b[1]-label[1]));
    if (!candidates.length) throw Error(`No interior label for ${f.properties.nhood}`);
    label=candidates[0];
  }
  return {name:f.properties.nhood,polygons,bounds,label};
}).sort((a,b)=>a.name.localeCompare(b.name));
console.log(`${neighborhoods.length} measured neighborhood polygons`);
// Regional flight arrivals are anchored to measured city street segments, not a fabricated drive network.
const { datasf, worldLines } = await import('./geo-base.mjs');
const vm = await import('node:vm');
const context={window:{NYC:{}}};
vm.runInNewContext(fs.readFileSync(new URL('../js/sf-geodata.js',import.meta.url),'utf8'),context);
const geo=context.window.NYC.GEO;
const segments=datasf('streets','city').filter(f=>['TWIN PEAKS BLVD','MARINE DR','STEINER ST'].includes(f.properties.streetname)).flatMap(f=>worldLines(f.geometry).flatMap(line=>line.slice(1).map((b,i)=>({road:f.properties.streetname,a:line[i],b}))));
const tiles=new Map();
function height(x,z) {
  const tx=Math.floor(x/1000),tz=Math.floor(z/1000),key=`${tx}-${tz}`;
  if(!tiles.has(key)) {
    const b=fs.readFileSync(new URL(`../data/region/city-${key}.bin`,import.meta.url));const n=b.readUInt32LE(4);
    tiles.set(key,{h:JSON.parse(b.subarray(8,8+n)),b,offset:8+n});
  }
  const {h,b,offset}=tiles.get(key),i=Math.round((x-h.originX)/h.cell),j=Math.round((z-h.originZ)/h.cell);
  return h.minH+b.readUInt16LE(offset+(j*h.w+i)*2)*h.scale;
}
function nearest(road,target) {
  let best;
  for(const seg of segments.filter(s=>s.road===road)) {
    const [ax,az]=seg.a,[bx,bz]=seg.b,dx=bx-ax,dz=bz-az;
    const t=Math.max(0,Math.min(1,((target[0]-ax)*dx+(target[1]-az)*dz)/(dx*dx+dz*dz||1)));
    const x=ax+t*dx,z=az+t*dz,d=Math.hypot(x-target[0],z-target[1]);
    if(!best||d<best.d)best={...seg,x,z,d};
  }
  return best;
}
const twin=segments.filter(s=>s.road==='TWIN PEAKS BLVD').map(s=>({...s,x:(s.a[0]+s.b[0])/2,z:(s.a[1]+s.b[1])/2})).sort((a,b)=>height(b.x,b.z)-height(a.x,a.z))[0];
const fort=geo.landmarks['Fort Point'];const painted=geo.landmarks['Painted Ladies'];
if(!fort||!painted)throw Error('Missing sourced landmark');
const gateTarget=geo.bridges.goldenGate.towers[0].c;
const regional={
  twinpeaks:{name:'Twin Peaks',...twin,target:[0,0]},
  goldengate:{name:'Golden Gate viewpoint',...nearest('MARINE DR',[fort.x,fort.z]),target:gateTarget},
  paintedladies:{name:'Painted Ladies',...nearest('STEINER ST',[painted.x,painted.z]),target:[painted.x,painted.z]}
};
for(const d of Object.values(regional)) { d.heading=Math.atan2(d.target[0]-d.x,d.target[1]-d.z);d.mode='helicopter';delete d.d; }
const output={source:'https://data.sfgov.org/resource/j2bu-swwd.geojson',rawSha256:crypto.createHash('sha256').update(raw).digest('hex'),neighborhoods,regional};
