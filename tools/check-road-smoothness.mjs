// tools/check-road-smoothness.mjs — how bumpy the baked terrain is along the streets (decides P2.3 / PLAN.md D5).
// Along every road-graph link's centreline, samples the terrain every 1 m and takes the second difference over 5 m
// windows, |h(s + 5) - 2 h(s) + h(s - 5)| / 25 (m^-1: the change of grade per metre). Reports p50 / p95 / max overall and
// per link, the worst 20 links by p95, and writes docs/reports/road-smoothness-<box>.md.
//
// usage: node tools/check-road-smoothness.mjs [box]
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { ROOT } from './geo-base.mjs';
import { readBin } from './geo-terrain.mjs';

const box = process.argv[2] || 'slice';
const STEP = 1;
const WIN = 5;
const THRESHOLD = 0.04; // m^-1: p95 above this is a visible bump at driving speed (P2.3)
const SKIP = 0; // metres left out at each link end (junction crests count too; 12 m gives p95 0.0026 in the slice)

const ctx = vm.createContext({ window: {} });
vm.runInContext(fs.readFileSync(path.join(ROOT, 'js/sf-geodata.js'), 'utf8'), ctx);
const GEO = ctx.window.NYC.GEO;
const { header: T, payload } = readBin(path.join(ROOT, `data/terrain-${box}.bin`));
const q = new Uint16Array(payload.buffer, payload.byteOffset, T.w * T.h);
const heightAt = (x, z) => {
  const fi = Math.min(T.w - 1.001, Math.max(0, (x - T.originX) / T.cell));
  const fj = Math.min(T.h - 1.001, Math.max(0, (z - T.originZ) / T.cell));
  const i = Math.floor(fi), j = Math.floor(fj), tx = fi - i, tz = fj - j;
  const v = (a, b) => T.minH + q[b * T.w + a] * T.scale;
  const a = v(i, j) + (v(i + 1, j) - v(i, j)) * tx;
  const b = v(i, j + 1) + (v(i + 1, j + 1) - v(i, j + 1)) * tx;
  return a + (b - a) * tz;
};

const RG = GEO.roadGraph;
const pct = (arr, p) => arr[Math.min(arr.length - 1, Math.floor(p * (arr.length - 1)))];
const all = [];
const rows = [];
for (const [k, link] of RG.links.entries()) {
  const [a, b, ni, , , , inner, flags] = link;
  if (flags & (1 | 2)) continue; // freeways & tunnels don't follow the ground
  const pts = [[RG.nodes[2 * a], RG.nodes[2 * a + 1]]];
  for (let i = 0; i < inner.length; i += 2) pts.push([inner[i], inner[i + 1]]);
  pts.push([RG.nodes[2 * b], RG.nodes[2 * b + 1]]);
  // resample every STEP m
  const prof = [];
  let carry = 0;
  for (let i = 0; i + 1 < pts.length; i++) {
    const [x0, z0] = pts[i], [x1, z1] = pts[i + 1];
    const len = Math.hypot(x1 - x0, z1 - z0);
    for (let s = carry; s < len; s += STEP) prof.push(heightAt(x0 + ((x1 - x0) * s) / len, z0 + ((z1 - z0) * s) / len));
    carry = (STEP - ((len - carry) % STEP)) % STEP;
  }
  const curv = [];
  for (let s = SKIP + WIN; s < prof.length - SKIP - WIN; s++) curv.push(Math.abs(prof[s + WIN] - 2 * prof[s] + prof[s - WIN]) / (WIN * WIN));
  if (!curv.length) continue;
  all.push(...curv);
  curv.sort((p, r) => p - r);
  const grade = Math.abs(prof[prof.length - 1] - prof[0]) / Math.max(1, prof.length - 1);
  rows.push({ k, name: RG.names[ni], len: prof.length, grade, p50: pct(curv, 0.5), p95: pct(curv, 0.95), max: curv[curv.length - 1] });
}
all.sort((p, r) => p - r);
const overall = { samples: all.length, links: rows.length, p50: pct(all, 0.5), p95: pct(all, 0.95), max: all[all.length - 1] };
const verdict = overall.p95 > THRESHOLD ? 'CONFORM' : 'SKIP conforming';
const worst = rows.slice().sort((p, r) => r.p95 - p.p95).slice(0, 20);
const f = (v) => v.toFixed(4);
const report = [
  `# Road smoothness (${box})`,
  '',
  `Generated by \`tools/check-road-smoothness.mjs\`. Second difference of the baked terrain along every link centreline (1 m samples,`,
  `${WIN} m windows, ${SKIP} m left out at each end), in m⁻¹. Threshold for conforming (P2.3): p95 > ${THRESHOLD}.`,
  '',
  `| Samples | Links | p50 | p95 | max | Verdict |`,
  `|---|---|---|---|---|---|`,
  `| ${overall.samples} | ${overall.links} | ${f(overall.p50)} | ${f(overall.p95)} | ${f(overall.max)} | ${verdict} |`,
  '',
  '## Worst 20 links by p95',
  '',
  '| Link | Name | Length (m) | Mean grade | p50 | p95 | max |',
  '|---|---|---|---|---|---|---|',
  ...worst.map((r) => `| ${r.k} | ${r.name} | ${r.len} | ${(r.grade * 100).toFixed(1)}% | ${f(r.p50)} | ${f(r.p95)} | ${f(r.max)} |`),
  ''
].join('\n');
fs.mkdirSync(path.join(ROOT, 'docs/reports'), { recursive: true });
fs.writeFileSync(path.join(ROOT, `docs/reports/road-smoothness-${box}.md`), report);
console.log(JSON.stringify({ ...overall, verdict }));
console.log(worst.slice(0, 5).map((r) => `${r.name} p95 ${f(r.p95)} max ${f(r.max)}`).join('\n'));
